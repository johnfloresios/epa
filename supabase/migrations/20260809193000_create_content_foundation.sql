create unique index if not exists idx_questions_public_id
  on public.questions (public_id);

do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'questions'
      and column_name = 'question'
  ) then
    execute '
      update public.questions
      set question_text = coalesce(question_text, question)
      where question_text is null
    ';
  end if;
end
$$;

do $$
declare
  question_id_type text;
begin
  select c.data_type
  into question_id_type
  from information_schema.columns c
  where c.table_schema = 'public'
    and c.table_name = 'questions'
    and c.column_name = 'id';

  if question_id_type = 'bigint' then
    execute '
      create table if not exists public.question_choices (
        id uuid primary key default gen_random_uuid(),
        question_id bigint not null references public.questions (id) on delete cascade,
        choice_text text not null,
        is_correct boolean not null default false,
        sort_order integer not null default 0,
        created_at timestamptz not null default timezone(''utc'', now()),
        updated_at timestamptz not null default timezone(''utc'', now())
      )
    ';
  else
    execute '
      create table if not exists public.question_choices (
        id uuid primary key default gen_random_uuid(),
        question_id uuid not null references public.questions (id) on delete cascade,
        choice_text text not null,
        is_correct boolean not null default false,
        sort_order integer not null default 0,
        created_at timestamptz not null default timezone(''utc'', now()),
        updated_at timestamptz not null default timezone(''utc'', now())
      )
    ';
  end if;
end
$$;

