create or replace function public.set_timestamp_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists set_certification_sections_updated_at on public.certification_sections;
create trigger set_certification_sections_updated_at
before update on public.certification_sections
for each row
execute function public.set_timestamp_updated_at();

